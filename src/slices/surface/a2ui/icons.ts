/** Every icon name that is drawn. */
export const ICON_NAMES = [...ICONS.keys()];

/** The icon of `name`, or undefined when that is none of the standard's names. */
export const iconOf = (name: unknown): LucideIcon | undefined => ICONS.get(name);

/** An icon's name in words, such as "shopping cart". */
export const iconWords = (name: unknown): string => (ICONS.has(name) ? String(name).replace(/[A-Z]/g, (letter) => ` ${letter.toLowerCase()}`) : "icon");
